#!/usr/bin/env python3
"""Regenerate art/characters/player/player_frames.tres from the downloaded PixelLab frames.

Scans art/characters/player/{idle,walk,tool}/{south,north,east,west}/*.png (numerically
sorted) and emits a Godot 4 SpriteFrames .tres with one animation per action+direction
(idle_south, walk_east, tool_north, ...). Keep this script in sync with scripts/player.gd's
animation-name convention ("<action>_<facing>").

Rules encoded here:
  - idle/walk loop; tool does NOT loop (scripts/player.gd unlocks movement on
    animation_finished, which never fires on looping animations).
  - speeds: idle 5 fps, walk 8 fps, tool 10 fps.

Usage: python3 tools/build_player_frames.py   (from the repo root)
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLAYER_DIR = os.path.join(ROOT, "art", "characters", "player")
OUT_PATH = os.path.join(PLAYER_DIR, "player_frames.tres")

ACTIONS = [
    ("idle", True, 5.0),
    ("walk", True, 8.0),
    ("tool", False, 10.0),
]
DIRECTIONS = ["south", "north", "east", "west"]


def main() -> int:
    ext_resources = []  # (id, res_path)
    animations = []  # (name, loop, speed, [ext ids])
    next_id = 1
    for action, loop, speed in ACTIONS:
        for direction in DIRECTIONS:
            frame_dir = os.path.join(PLAYER_DIR, action, direction)
            if not os.path.isdir(frame_dir):
                print(f"ERROR: missing frames dir {frame_dir}", file=sys.stderr)
                return 1
            frames = sorted(
                (f for f in os.listdir(frame_dir) if f.endswith(".png")),
                key=lambda f: int(os.path.splitext(f)[0]),
            )
            if not frames:
                print(f"ERROR: no frames in {frame_dir}", file=sys.stderr)
                return 1
            ids = []
            for frame in frames:
                res_path = f"res://art/characters/player/{action}/{direction}/{frame}"
                ext_resources.append((next_id, res_path))
                ids.append(next_id)
                next_id += 1
            animations.append((f"{action}_{direction}", loop, speed, ids))

    lines = [
        f'[gd_resource type="SpriteFrames" load_steps={len(ext_resources) + 1} format=3]',
        "",
        "; GENERATED by tools/build_player_frames.py — edit that script, not this file.",
        "; Player animation frames (PixelLab character 6ee1466d-dd09-4732-9e99-ad57c9efbfab;",
        "; see art/characters/README.md for provenance).",
        "",
    ]
    for rid, res_path in ext_resources:
        lines.append(f'[ext_resource type="Texture2D" path="{res_path}" id="{rid}"]')
    lines.append("")
    lines.append("[resource]")
    anim_blocks = []
    for name, loop, speed, ids in animations:
        frames = ", ".join(
            f'{{\n"duration": 1.0,\n"texture": ExtResource("{fid}")\n}}' for fid in ids
        )
        anim_blocks.append(
            f'{{\n"frames": [{frames}],\n"loop": {str(loop).lower()},\n'
            f'"name": &"{name}",\n"speed": {speed}\n}}'
        )
    lines.append("animations = [" + ", ".join(anim_blocks) + "]")
    lines.append("")
    with open(OUT_PATH, "w") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {OUT_PATH}: {len(animations)} animations, {len(ext_resources)} frames")
    return 0


if __name__ == "__main__":
    sys.exit(main())
