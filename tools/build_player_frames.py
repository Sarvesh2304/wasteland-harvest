#!/usr/bin/env python3
"""Regenerate <name>_frames.tres from downloaded PixelLab frames for every game character.

Originally player-only (hence the filename, kept so existing docs/references stay valid);
generalized in Phase 6's Art pass 1 when the 3 town NPCs got real art through the exact same
pipeline. Scans art/characters/<name>/{action}/{south,north,east,west}/*.png (numerically
sorted) and emits a Godot 4 SpriteFrames .tres with one animation per action+direction
(idle_south, walk_east, tool_north, ...). Keep this script in sync with scripts/player.gd's /
scripts/npc.gd's shared animation-name convention ("<action>_<facing>").

Rules encoded here:
  - idle/walk loop; tool does NOT loop (scripts/player.gd unlocks movement on
    animation_finished, which never fires on looping animations).
  - speeds: idle 5 fps everywhere; walk 8 fps for the player but 6 fps for NPCs, whose
    24 px/s amble (npc.gd WALK_SPEED, vs the player's 56) would read as foot-sliding
    against the player's cycle rate; tool 10 fps.
  - NPCs have NO tool animation — they never use tools (see art/characters/README.md's
    animation-scope note), so generating/wiring one would be dead weight.

Usage: python3 tools/build_player_frames.py [character ...]   (from the repo root)
       With no arguments, rebuilds every character listed in CHARACTERS.
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHARACTERS_DIR = os.path.join(ROOT, "art", "characters")

DIRECTIONS = ["south", "north", "east", "west"]

# name -> (actions [(action, loop, fps)], PixelLab character id for the provenance comment)
CHARACTERS = {
    "player": (
        [("idle", True, 5.0), ("walk", True, 8.0), ("tool", False, 10.0)],
        "6ee1466d-dd09-4732-9e99-ad57c9efbfab",
    ),
    "mayor_harlan": (
        [("idle", True, 5.0), ("walk", True, 6.0)],
        "dcb351f7-384f-4234-b907-7939fcfbfdc6",
    ),
    "marta": (
        [("idle", True, 5.0), ("walk", True, 6.0)],
        "d3193faa-ca86-41ee-857e-7df8b0294070",
    ),
    "scout_kael": (
        [("idle", True, 5.0), ("walk", True, 6.0)],
        "4fe49946-1b70-4661-8a47-140649d03972",
    ),
    "rancher_silas": (
        [("idle", True, 5.0), ("walk", True, 6.0)],
        "c8dd77da-5f26-4642-9b07-20ddbda6f223",
    ),
}


def build_character(name: str) -> int:
    actions, pixellab_id = CHARACTERS[name]
    char_dir = os.path.join(CHARACTERS_DIR, name)
    out_path = os.path.join(char_dir, f"{name}_frames.tres")
    ext_resources = []  # (id, res_path)
    animations = []  # (name, loop, speed, [ext ids])
    next_id = 1
    for action, loop, speed in actions:
        for direction in DIRECTIONS:
            frame_dir = os.path.join(char_dir, action, direction)
            if not os.path.isdir(frame_dir):
                print(f"ERROR: missing frames dir {frame_dir}", file=sys.stderr)
                return 1
            frames = sorted(
                (f for f in os.listdir(frame_dir) if f.endswith(".png")),
                key=lambda f: int(os.path.splitext(f)[0]),
            )
            if not frames:
                print(f"ERROR: no frames in {frame_dir}", file=sys.stderr)
                return 1
            ids = []
            for frame in frames:
                res_path = f"res://art/characters/{name}/{action}/{direction}/{frame}"
                ext_resources.append((next_id, res_path))
                ids.append(next_id)
                next_id += 1
            animations.append((f"{action}_{direction}", loop, speed, ids))

    lines = [
        f'[gd_resource type="SpriteFrames" load_steps={len(ext_resources) + 1} format=3]',
        "",
        "; GENERATED by tools/build_player_frames.py — edit that script, not this file.",
        f"; {name} animation frames (PixelLab character {pixellab_id};",
        "; see art/characters/README.md for provenance).",
        "",
    ]
    for rid, res_path in ext_resources:
        lines.append(f'[ext_resource type="Texture2D" path="{res_path}" id="{rid}"]')
    lines.append("")
    lines.append("[resource]")
    anim_blocks = []
    for anim_name, loop, speed, ids in animations:
        frames = ", ".join(
            f'{{\n"duration": 1.0,\n"texture": ExtResource("{fid}")\n}}' for fid in ids
        )
        anim_blocks.append(
            f'{{\n"frames": [{frames}],\n"loop": {str(loop).lower()},\n'
            f'"name": &"{anim_name}",\n"speed": {speed}\n}}'
        )
    lines.append("animations = [" + ", ".join(anim_blocks) + "]")
    lines.append("")
    with open(out_path, "w") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {out_path}: {len(animations)} animations, {len(ext_resources)} frames")
    return 0


def main() -> int:
    names = sys.argv[1:] or list(CHARACTERS)
    for name in names:
        if name not in CHARACTERS:
            print(f"ERROR: unknown character '{name}' (known: {', '.join(CHARACTERS)})",
                  file=sys.stderr)
            return 1
        status = build_character(name)
        if status != 0:
            return status
    return 0


if __name__ == "__main__":
    sys.exit(main())
