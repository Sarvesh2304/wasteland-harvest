#!/usr/bin/env python3
"""Regenerate the Wasteland Harvest soundtrack (deterministic, fixed seeds).

    python3 tools/audio/music/build_all.py                 # all tracks
    python3 tools/audio/music/build_all.py title spring    # just these
    python3 tools/audio/music/build_all.py --png /tmp/rev  # + waveform/spectrogram PNGs
    python3 tools/audio/music/build_all.py --jobs 2        # parallel workers (default: CPUs)

Writes OGG Vorbis (q6, 44.1 kHz stereo) to audio/music/, a manifest
(audio/music/music_manifest.json) and the "Music" section of audio/README.md.
Requires numpy, scipy and ffmpeg (with libvorbis); Pillow only for --png.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
OUT_DIR = os.path.join(REPO, "audio", "music")
README = os.path.join(REPO, "audio", "README.md")

import numpy as np  # noqa: E402

from engine import analysis  # noqa: E402
from engine.master import decode, encode_ogg, ffmpeg_loudness, master  # noqa: E402
from engine.mixer import render_song  # noqa: E402
from scores import TRACKS, load  # noqa: E402


def build_one(name: str, png_dir: str | None = None, out_dir: str = OUT_DIR) -> dict:
    t0 = time.time()
    song = load(name).build()
    mix, stats, _ = render_song(song)
    if not np.all(np.isfinite(mix)):
        raise RuntimeError(f"{name}: mix contains NaN/inf")
    m = song.master
    y, info = master(mix, m["target_lufs"], m["ceiling_dbtp"], m.get("eq"), m.get("glue"),
                     loop=song.loop, sr=song.sr)
    if not np.all(np.isfinite(y)) or info["lufs"] < -40:
        raise RuntimeError(f"{name}: mastered output invalid (lufs {info['lufs']})")
    path = os.path.join(out_dir, f"{name}.ogg")
    meta = {"title": song.meta.get("title", name), "artist": "Wasteland Harvest OST",
            "album": "Wasteland Harvest", "comment": "generated by tools/audio/music/build_all.py"}
    if song.loop:
        meta.update({"LOOPSTART": 0, "LOOPLENGTH": y.shape[-1]})
    encode_ogg(y, path, song.sr, 6, meta)
    dec = decode(path, song.sr)
    fl = ffmpeg_loudness(path)
    seam = analysis.seam_check(dec, y, song.sr) if song.loop else None
    bal = analysis.spectral_balance(y, song.sr)
    lint = analysis.harmonic_lint(song)
    res = {
        "name": name, "file": f"audio/music/{name}.ogg", "loop": song.loop,
        "bpm": song.bpm, "beats_per_bar": song.bpb, "bars": song.n_bars, "key": song.meta.get("key", song.key),
        "samples": int(y.shape[-1]), "decoded_samples": int(dec.shape[-1]),
        "seconds": round(y.shape[-1] / song.sr, 3), "lufs": round(info["lufs"], 2),
        "true_peak": round(info["true_peak"], 2), "ffmpeg_I": fl["I"], "ffmpeg_TP": fl["TP"],
        "ffmpeg_LRA": fl["LRA"], "seam": seam, "balance": bal, "lint": lint,
        "use": song.meta.get("use", ""), "sections": [(s.name, s.start_bar, s.bars) for s in song.sections],
        "parts": stats, "render_s": round(time.time() - t0, 1), "title": song.meta.get("title", name),
        "clip_samples": int(np.sum(np.abs(dec) >= 0.999)),
    }
    if png_dir:
        os.makedirs(png_dir, exist_ok=True)
        secs = [(s.name, s.start_bar * song.bpb * song.spb) for s in song.sections] if song.sections else [("all", 0.0)]
        analysis.waveform_png(dec, os.path.join(png_dir, f"{name}_wave.png"), f"{name}  {res['seconds']}s  "
                              f"{fl['I']} LUFS  TP {fl['TP']} dBTP", secs, song.sr)
        analysis.spectrogram_png(dec, os.path.join(png_dir, f"{name}_spec.png"), f"{name} spectrogram",
                                 secs, song.sr)
        with open(os.path.join(png_dir, f"{name}_report.txt"), "w") as f:
            f.write(analysis.band_report(dec, secs, song.sr) + "\n\n")
            f.write(json.dumps({k: v for k, v in res.items() if k != "parts"}, indent=1, default=str) + "\n")
            f.write(json.dumps(stats, indent=1) + "\n")
    return res


def _worker(args):
    name, png_dir = args
    try:
        return build_one(name, png_dir)
    except Exception as e:  # pragma: no cover - report and keep going
        import traceback
        return {"name": name, "error": f"{e}\n{traceback.format_exc()}"}


def fmt_time(s: float) -> str:
    return f"{int(s // 60)}:{s % 60:05.2f}"


def write_manifest(results: list[dict]):
    path = os.path.join(OUT_DIR, "music_manifest.json")
    old = {}
    if os.path.exists(path):
        try:
            old = {t["name"]: t for t in json.load(open(path))["tracks"]}
        except Exception:
            old = {}
    for r in results:
        if "error" in r:
            continue
        old[r["name"]] = {k: r[k] for k in ("name", "file", "title", "loop", "key", "bpm", "beats_per_bar",
                                            "bars", "samples", "seconds", "use")}
        old[r["name"]]["lufs"] = r["ffmpeg_I"]
        old[r["name"]]["true_peak_dbtp"] = r["ffmpeg_TP"]
    order = [n for n in TRACKS if n in old]
    with open(path, "w") as f:
        json.dump({"sample_rate": 44100, "tracks": [old[n] for n in order]}, f, indent=2)
        f.write("\n")
    return [old[n] for n in order]


BEGIN, END = "<!-- MUSIC:BEGIN (generated by tools/audio/music/build_all.py) -->", "<!-- MUSIC:END -->"


def write_readme(tracks: list[dict]):
    rows = []
    for t in tracks:
        meter = f"{int(t['beats_per_bar'])}/4"
        loop = f"loop ({t['bars']} bars)" if t["loop"] else "one-shot"
        rows.append(f"| `{t['name']}.ogg` | {t['key']} | {t['bpm']:g} BPM, {meter} | {fmt_time(t['seconds'])} | "
                    f"{loop} | {t['lufs']} | {t['use']} |")
    body = "\n".join([
        BEGIN,
        "## Music",
        "",
        "Original soundtrack, fully code-synthesised (no samples): Karplus-Strong guitar / banjo / harp,",
        "phrase-modelled harmonica, accordion and slide lead, FM e-piano and bells, additive music box /",
        "marimba / felt piano, detuned-saw pads, synthesised folk percussion and ruins metals, convolution",
        "reverb with generated impulse responses. Frontier folk + warm chiptune + ambient.",
        "",
        "* **Regenerate:** `python3 tools/audio/music/build_all.py` (deterministic; optional track names,",
        "  `--png DIR` for waveform/spectrogram review images). Needs numpy, scipy and ffmpeg w/ libvorbis.",
        "* **Scores** are readable text next to the synth code: `tools/audio/music/scores/<track>.py`",
        "  (chord charts + melody notation; the shared leitmotif lives in `scores/leitmotif.py`).",
        "* **Format:** OGG Vorbis q6, 44.1 kHz stereo, mastered to about -16..-14 LUFS integrated,",
        "  true peak <= -1 dBTP.",
        "* **Loops:** every track marked *loop* is exactly an integer number of bars long and loops",
        "  sample-seamlessly from the last sample back to sample 0 (reverb tails are pre-wrapped onto the",
        "  start). Enable looping on the stream (`AudioStreamOggVorbis.loop = true`, `loop_offset = 0`) or",
        "  tick *Loop* in the import dock. Files also carry `LOOPSTART=0` / `LOOPLENGTH` tags.",
        "  `audio/music/music_manifest.json` lists key / BPM / bars / sample length for beat-synced",
        "  transitions (e.g. switch tracks on a bar line).",
        "* **Leitmotif:** the 8-bar main theme from `title.ogg` recurs throughout: quoted in spring, night,",
        "  festival (as a reel), sad (in B minor), the victory/new-day stingers, and in a broken, phrygian",
        "  form in the ruins tracks.",
        "",
        "| File | Key | Tempo | Length | Loop | LUFS | Intended use |",
        "|---|---|---|---|---|---|---|",
        *rows,
        "",
        END,
    ])
    if os.path.exists(README):
        txt = open(README).read()
        if BEGIN in txt and END in txt:
            a = txt.index(BEGIN)
            b = txt.index(END) + len(END)
            txt = txt[:a] + body + txt[b:]
        else:
            txt = txt.rstrip() + "\n\n" + body + "\n"
    else:
        txt = "# Audio\n\nGame audio assets for Wasteland Harvest.\n\n" + body + "\n"
    with open(README, "w") as f:
        f.write(txt)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("tracks", nargs="*", help="track names (default: all)")
    ap.add_argument("--jobs", type=int, default=min(4, os.cpu_count() or 1))
    ap.add_argument("--png", default=None, help="directory for review PNGs / reports")
    ap.add_argument("--no-readme", action="store_true")
    a = ap.parse_args()
    names = a.tracks or list(TRACKS)
    for n in names:
        if n not in TRACKS:
            sys.exit(f"unknown track {n!r}; known: {', '.join(TRACKS)}")
    os.makedirs(OUT_DIR, exist_ok=True)
    t0 = time.time()
    results = []
    # longest tracks first so parallel workers finish together
    names.sort(key=lambda n: -TRACKS[n])
    if a.jobs > 1 and len(names) > 1:
        import multiprocessing as mp
        with mp.get_context("fork").Pool(a.jobs, maxtasksperchild=1) as pool:
            for r in pool.imap_unordered(_worker, [(n, a.png) for n in names]):
                results.append(r)
                _print_result(r)
    else:
        for n in names:
            r = _worker((n, a.png))
            results.append(r)
            _print_result(r)
    errs = [r for r in results if "error" in r]
    tracks = write_manifest(results)
    if not a.no_readme:
        write_readme(tracks)
    print(f"done in {time.time() - t0:.0f}s; {len(results) - len(errs)} ok, {len(errs)} failed")
    if errs:
        for r in errs:
            print(r["name"], r["error"])
        sys.exit(1)


def _print_result(r):
    if "error" in r:
        print(f"[FAIL] {r['name']}: {r['error'].splitlines()[0]}")
        return
    seam = r["seam"]
    s = (f"seam step {seam['seam_step']:.4f} (x{seam['step_ratio']:.2f} local, master x{seam['pre_step_ratio']:.2f}) "
         f"hf@seam {seam['hf_at_seam']:.4f}/{seam['pre_hf_at_seam']:.4f} (before {seam['hf_before']:.4f})"
         if seam else "one-shot")
    ok_len = "len ok" if r["decoded_samples"] == r["samples"] else f"LEN {r['decoded_samples']}!={r['samples']}"
    print(f"[ok] {r['name']:<18} {fmt_time(r['seconds'])}  I {r['ffmpeg_I']} LUFS  TP {r['ffmpeg_TP']} dBTP  "
          f"{ok_len}  {s}  clip {r['clip_samples']}  ({r['render_s']}s)")
    b = r["balance"]
    print(f"     balance: " + "  ".join(f"{k} {v:.1f}" for k, v in b.items()))
    for w in r["lint"][:12]:
        print("     lint:", w)


if __name__ == "__main__":
    main()
