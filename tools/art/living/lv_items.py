"""Two item icons for Milestone D (art/items/, 16 x 16), drawn with the items pipeline's own kit
(tools/art/items/ia_lib.py + its private colour ramps) so they match the other icons exactly:
1 px margin, top-left light, selective outline (dark local colour above / left, warm #281a0b
below / right).

  vault_seeds.png      a sealed steel seed canister from the Northgate vault: clamped lid, a
                       cream label with a stencilled green sprout
  festival_ribbon.png  a prize rosette: pleated red ring, gold heart, two notched tails

They are not in data/items.json yet, so the items pipeline would not write them; this kit does.
"""
from __future__ import annotations

import math

import ia_lib as L
from ia_lib import Ramp
from ia_common import C


def vault_seeds():
    steel = Ramp(C.STEEL[1:])
    dark = Ramp(C.STEEL[:4])
    label = Ramp(C.CLOTH_WHITE)
    sprout = C.LEAF
    s, lays = L.icon("""
        ................
        ................
        ......kkkk......
        .....kttttk.....
        ....tttttttt....
        ....kkkkkkkk....
        ....ssssssss....
        ....llllllll....
        ....llllllll....
        ....llllllll....
        ....llllllll....
        ....ssssssss....
        ....ssssssss....
        .....kkkkkk.....
        ................
        ................
    """, {
        "s": (steel, "cyl", {"axis": 90, "contrast": 2.0}),
        "l": (label, "cyl", {"axis": 90, "contrast": 1.4}),
        "t": (steel, "cyl", {"axis": 90, "contrast": 1.8, "sep": "outer", "sep_idx": 1}),
        "k": (dark, "cyl", {"axis": 90, "contrast": 1.6}),
    }, render=False)
    # the stencilled sprout on the label (after shading, before the outline)
    for (x, y, k) in ((8, 10, 2), (8, 9, 3), (7, 8, 4), (6, 7, 3), (9, 8, 3), (10, 7, 4)):
        s.put(x, y, sprout[k])
    # clamp latch on the seal ring and a glint down the lit side of the body
    s.put(11, 5, C.STEEL[5])
    s.put(5, 11, C.STEEL[5])
    return s.render()


def festival_ribbon():
    red = Ramp(C.PLASTIC_RED)
    gold = Ramp(C.GOLD)
    s = L.Sprite()
    t = s.layer(red, "flat", base=2, lit=3, dark=1)
    t.ascii(L.grid("""
        ................
        ................
        ................
        ................
        ................
        ................
        ................
        ................
        .....##..##.....
        .....##..##.....
        ....##....##....
        ....##....##....
        ...##......##...
        ...#.#....#.#...
        ................
        ................
    """))
    ring = s.layer(red, "flat", base=3, lit=4, dark=2, sep="outer", sep_idx=0)
    cx, cy, r = 8.0, 6.9, 4.9
    ring.ellipse(cx, cy, r, r)
    ys, xs = ring.mask.nonzero()
    pleats = []
    for (x, y) in zip(xs, ys):                       # pleats: alternating light / dark wedges
        dx, dy = x + 0.5 - cx, y + 0.5 - cy
        ang = math.degrees(math.atan2(dy, dx))
        k = 3 if int((ang + 360) // 30) % 2 else 2
        if dx + dy < -3.5:
            k += 1                                   # lit upper-left
        elif dx + dy > 3.5:
            k -= 1                                   # shaded lower-right
        pleats.append(((x, y), k))
    for (p, k) in pleats:
        ring.set([p], k)
    heart = s.layer(gold, "sphere", contrast=1.6, sep="outer", sep_idx=1)
    heart.ellipse(cx, cy, 2.4, 2.4)
    s.put(7, 6, C.GOLD[5])
    return s.render()


ICONS = {"vault_seeds": vault_seeds, "festival_ribbon": festival_ribbon}
