"""The 13 fish icons (art/items/<id>.png, 16 x 16), drawn with the items pipeline's own kit
(tools/art/items/ia_lib.py) so they match the other item icons: 1 px clear margin, light from
the top-left, selective outline (dark local colour above / left, warm #281a0b below / right).

Every fish faces left. They are told apart by silhouette first and colour second:

  mud_minnow         a stubby little silt-brown fish, the smallest of them
  shellback_crawdad  a brick-red crawdad seen from above, two big claws up
  rustgill_carp      a deep, humped bronze carp with rust-orange gill plates and a barbel
  sun_perch          a round gold sunfish disc with an orange breast, teal bars and a spiny crest
  silver_dace        a slim silver-blue dart with a huge forked tail
  ash_trout          a fat ash-grey trout leaping up-right, speckled, with a faded pink band
  bog_eel            a peat-dark eel coiled in an S, yellow belly, fin ridge along its back
  sludge_catfish     a flat-headed swamp-green catfish with whiskers, dripping oily sludge
  frostfin           an ice-blue fish with crystalline, shard-like fins
  iron_pike          a long gunmetal pike corner to corner, duck-bill jaw, rivet spots
  glowfin            a deep-blue fish whose sail fins and flank spots glow rad green
  two_headed_perch   a yellow-green barred perch with two heads on one body
  old_mayor          the legendary catfish: fills the icon, long cream whiskers, an old scar,
                     a rusted hook still in its lip
"""
from __future__ import annotations

import ia_lib as L
