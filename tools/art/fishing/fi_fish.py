import palette as P

EYE = "#1c140c"            # fish eyes (warm near-black, never pure black)
EYE_GLINT = "#f4ecd8"


def _ramp(cols, outline=None):
    return Ramp(cols, outline)


def draw(rows, layers, legend=None, marks=None, render=True):
    """L.icon plus `marks`: char -> (layer key, colour). The pixel joins that layer's mask (so the
    layer's shading sees no hole) and is then painted `colour` before the outline pass."""
    marks = marks or {}
    s, lays = L.icon(rows, layers, legend, render=False)
    for j, row in enumerate(L.grid(rows)):
        for i, ch in enumerate(row):
            if ch in marks:
                key, col = marks[ch]
                lays[key].px((i, j))
                s.put(i, j, col, lays[key].ramp)
    if not render:
        return s, lays
    return s.render()


def painted(rows, ramps: dict, legend: dict, sep: dict | None = None):
    """Hand-shaded icon: every char of `rows` names a ramp index explicitly.

    ramps:  key -> Ramp; one layer per key, drawn in this order (bottom to top)
    legend: char -> (ramp key, index) | ("put", colour). Digits default to ("b", digit) and
            a/b/c/d to ("v", 0..3) when those ramps exist.
    sep:    key -> sep_idx: give that layer a 1 px separation contour over the ones below
    The kit's outline pass still adds the selective outline round the whole silhouette."""
    sep = sep or {}
    legend = dict(legend)
    if "b" in ramps:
        for d in range(len(ramps["b"])):
            legend.setdefault(str(d), ("b", d))
    if "v" in ramps:
        for i, ch in enumerate("abcd"):
            legend.setdefault(ch, ("v", i))
    s = L.Sprite()
    lays = {}
    for key, ramp in ramps.items():
        opts = {"index": 0}
        if key in sep:
            opts.update(sep="outer", sep_idx=sep[key])
        lays[key] = s.layer(ramp, "solid", **opts)
    for j, row in enumerate(L.grid(rows)):
        for i, ch in enumerate(row):
            if ch == "." or ch not in legend:
                if ch != ".":
                    raise ValueError(f"painted: no legend for {ch!r}")
                continue
            val = legend[ch]
            if val[0] == "put":
                s.put(i, j, val[1])
            else:
                lays[val[0]].set([(i, j)], val[1])
    return s.render()


def _pts(rows, ch):
    return [(i, j) for j, row in enumerate(L.grid(rows)) for i, c in enumerate(row) if c == ch]


