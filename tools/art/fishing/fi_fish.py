def sun_perch():
    body = _ramp(P.PERCH_SUN_RAMP)
    belly = _ramp(P.PERCH_SUN_BELLY_RAMP)
    rows = """
        ................
        ................
        .....t.t.t......
        ....ttttttt.....
        ....bbbbbb...t..
        ...bbbbbbbb.tt..
        ..bebbbbbbb.t...
        ..bbbbbbbbbbt...
        ..bbbbbbbbbbt...
        ..vvvvvvvvv.t...
        ...vvvvvvvv.tt..
        ....vvvvvv...t..
        .....t..tt......
        ................
        ................
        ................
    """
    s, lays = draw(rows, {
        "t": (body, "flat", {"base": 2, "lit": 3, "dark": 1}),
        "b": (body, "inflate", {"contrast": 2.0, "base": 3}),
        "v": (belly, "inflate", {"contrast": 1.6, "base": 2}),
    }, render=False)
    s.put(3, 6, EYE)
    for (x, y) in ((6, 5), (6, 6), (6, 7), (6, 8), (9, 5), (9, 6), (9, 7), (9, 8)):
        s.put(x, y, P.PERCH_SUN_BAR, body)                  # teal bars
    s.put(4, 7, "#2a2016", body)                            # the dark ear spot ...
    s.put(4, 8, P.CAP_RED, body)                            # ... with its red rim
    return s.render()


