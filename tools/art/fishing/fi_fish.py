def eel(body: Ramp, belly: Ramp, fin: Ramp, eye=EYE, mouth=None, render=True):
    """The eel's S-coil (also used, lacquered, by fi_dishes.smoked_eel)."""
    s, lays = draw(EEL_ROWS, {
        "f": (fin, "flat", {"base": 2, "lit": 3, "dark": 1}),
        "t": (fin, "flat", {"base": 2, "lit": 3, "dark": 1}),
        "b": (body, "inflate", {"contrast": 2.0, "base": 3}),
        "v": (belly, "flat", {"base": 2, "lit": 3, "dark": 1}),
    }, marks={"e": ("b", eye), "m": ("v", mouth or body[0])}, render=False)
    return s.render() if render else (s, lays)


