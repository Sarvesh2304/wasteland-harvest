def glowfin():
    """Deep night-water blue with sail fins and flank spots that glow rad green; the glow spills
    over its outline (the outline round the glowing fins is a dim green, not warm brown)."""
    body = _ramp(P.GLOWFIN_RAMP)
    glow = _ramp(P.GLOWFIN_GLOW_RAMP, outline=P.GLOWFIN_HALO)
    rows = """
        ................
        ................
        .......gg.......
        ......ggg.......
        .....gggg...g...
        ....bbbbbbb.gg..
        ...bbbbbbbbbg...
        ..bebbbbbbbbg...
        ..bbbbbbbbbbgg..
        ...bbbbbbbb..g..
        .....gggg.......
        ......ggg.......
        .......g........
        ................
        ................
        ................
    """
    s, lays = draw(rows, {
        "g": (glow, "flat", {"base": 2, "lit": 3, "dark": 1}),
        "b": (body, "inflate", {"contrast": 2.0, "base": 3}),
    }, marks={"e": ("b", P.GLOWFIN_GLOW_RAMP[4])}, render=False)
    for (x, y) in ((5, 8), (7, 8), (9, 8), (6, 7), (8, 7)):
        s.put(x, y, P.GLOWFIN_GLOW_RAMP[3], body)          # photophores
    img = s.render()
    fins = lays["g"].mask
    near = L.dilate4(fins) & ~fins & (img[:, :, 3] > 0)
    for y, x in zip(*near.nonzero()):
        if not lays["b"].mask[y, x]:
            img[y, x] = L.rgba(P.GLOWFIN_HALO)               # glow spilling over the outline
    return img


