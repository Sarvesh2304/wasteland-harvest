from ia_common import C, crop_colors, ramp

LEAF = Ramp(C.LEAF[1:])            # 5: dark .. light
FRESH = Ramp(C.LEAF_FRESH[:5])
STEM = Ramp(C.STEM)


def cr(crop_id, i=0, n=5, **kw):
    return ramp(crop_colors(crop_id)[i], n, **kw)


def hexr(r, i):
    return L.to_hex(r[i])


def berries(spr, rmp, centres, r=1.75, hi=True, fat=0.15, sep="outer", bias=0.6, sep_idx=0):
    """A cluster of glossy little spheres, each its own layer (so each gets its own outline ring
    over the ones behind it) with a forced specular pixel at its upper-left."""
    import math
    for (cx, cy) in centres:
        lay = spr.layer(rmp, "sphere", contrast=2.2, sep=sep, bias=bias, sep_idx=sep_idx)
        lay.ellipse(cx, cy, r, r, fat=fat)
        if hi:
            hx, hy = int(math.floor(cx - r * 0.45)), int(math.floor(cy - r * 0.45))
            if lay.mask[hy, hx]:
                lay.set([(hx, hy)], len(rmp) - 1)
    return spr


