"""Seed packet icons: one shared packet template (worn cream paper, crimped top, a band in the
crop's main colour) with a tiny picture of the crop in its crops.json colours. seed_mixed is a
little drawstring cloth pouch instead."""
from __future__ import annotations

import numpy as np

import ia_lib as L
from ia_lib import Ramp
from ia_common import C, CROPS, ITEMS, crop_colors, ramp

PAPER = Ramp(C.PAPER)
LEAF = Ramp(C.LEAF[1:])
LEAF_LIGHT = Ramp(C.LEAF[2:])


def _band_ramp(crop_id):
    return ramp(crop_colors(crop_id)[0], 5, step=0.07)


def packet(band: Ramp, picture: np.ndarray | None) -> np.ndarray:
    s = L.Sprite()
    paper = s.layer(PAPER, "flat", base=3, lit=4, dark=2)
    paper.rect(3, 2, 12, 13)
    paper.px((3, 13), (12, 13), add=False)              # soft bottom corners
    # crimped top: alternating ridge shades
    for x in range(3, 13):
        paper.set([(x, 2)], 4 if x % 2 else 2)
    paper.set([(x, 3) for x in range(3, 13)], 1)       # fold shadow under the crimp
    b = s.layer(band, "flat", base=2, lit=3, dark=1, bevel_dark=False)
    b.rect(3, 4, 12, 5)
    b.set([(x, 4) for x in range(4, 12)], 3)
    img = s.render()
    if picture is not None:
        img = L.compose(img, L.offset(picture, 4, 6, 16, 16))
    return img


def mini(rows, layers, legend=None):
    """A tiny crop picture on an 8x8 canvas (fill inside x/y 1..6), auto-outlined."""
    return L.icon(rows, layers, legend, w=8, h=8)


def _r(crop_id, i=0, n=5, **kw):
    return ramp(crop_colors(crop_id)[i], n, **kw)


