def bowl(food: Ramp, chunks=(), chunk_rows=None, glow=None, garnish=None):
    s = L.Sprite()
    body = s.layer(ENAMEL, "cyl", axis=90, contrast=2.0)
    body.ascii(L.grid("""
        ..############..
        ..############..
        ...##########...
        ....########....
        .....######.....
    """), 0, 8)
    lip = s.layer(ENAMEL, "solid", index=4, sep="outer", sep_idx=1)
    lip.ascii(["..############.."], 0, 8)
    f = s.layer(food, "sphere", contrast=1.8, bias=0.3)
    f.ascii(L.grid(chunk_rows or """
        .....######.....
        ...##########...
        ..############..
        ..############..
    """), 0, 4)
    for (x, y, d) in chunks:
        f.nudge([(x, y)], d)
    if garnish:
        for (x, y, col) in garnish:
            s.put(x, y, col, food)
    img = s.render()
    if glow:
        for (x, y) in glow[1]:
            img[y, x] = L.rgba(glow[0])
    return img


