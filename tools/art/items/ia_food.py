def jar(content: Ramp, lid: Ramp, bits=(), lid_kind="cloth"):
    rows = """
        ................
        ................
        ....LLLLLLLL....
        ...LLLLLLLLLL...
        .....ssssss.....
        ....gccccccg....
        ...gccccccccg...
        ...gccccccccg...
        ...gccccccccg...
        ...gccccccccg...
        ...gccccccccg...
        ....gccccccg....
        .....gggggg.....
        ................
    """
    if lid_kind == "metal":
        rows = rows.replace("....LLLLLLLL....\n        ...LLLLLLLLLL...",
                            "................\n        ....LLLLLLLL....")
    s, lays = L.icon(rows, {
        "g": (GLASS, "cyl", {"axis": 90, "contrast": 2.0, "bias": 0.4}),
        "c": (content, "cyl", {"axis": 90, "contrast": 1.8, "gloss": True, "gloss_cut": 0.7}),
        "s": (Ramp(C.BURLAP[:4]), "solid", {"index": 2}),
        "L": (lid, "flat", {"base": 2, "lit": 3, "dark": 1, "sep": "outer", "sep_idx": 0}),
    }, render=False)
    for (x, y, d) in bits:
        lays["c"].nudge([(x, y)], d)
    return s.render()


