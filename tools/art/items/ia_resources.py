def _sack(band=None, emblem=None):
    sack = Ramp(C.BURLAP)
    soil = Ramp(C.SOIL[:5])
    layers = {
        "s": (sack, "inflate", {"contrast": 2.2, "bevel": 3}),
        "t": (Ramp(C.BURLAP[:4]), "flat", {"sep": "outer", "sep_idx": 0}),
        "d": (soil, "inflate", {"contrast": 2.0}),
    }
    if band:
        layers["b"] = (band, "flat", {"base": 2, "lit": 3, "dark": 1})
    rows = """
        ................
        ................
        ......d.dd......
        .....dddddd.....
        ......tttt......
        .....ssssss.....
        ....ssssssss....
        ...ssssssssss...
        ...ssssssssss...
        ...BBBBBBBBBB...
        ...ssssssssss...
        ...ssssssssss...
        ....ssssssss....
        ................
    """
    if not band:
        rows = rows.replace("B", "s")
    legend = {"B": "b"} if band else {}
    if emblem:
        legend["e"] = ("put", emblem)
        rows = rows.replace("...ssssssssss...\n        ...ssssssssss...\n        ....ssssssss....",
                            "...ssssessssss...\n        ...ssseeesssss...\n        ....ssssssss....")
    return L.icon(rows, layers, legend)


