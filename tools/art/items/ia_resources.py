def bottle_caps():
    import math
    tin = Ramp(C.TIN)
    red = Ramp(C.PLASTIC_RED)
    blue = Ramp(C.CLOTH_BLUE)
    s = L.Sprite()
    for (cx, cy, top) in ((5.0, 6.0, blue), (11.0, 6.6, tin), (7.6, 10.4, red)):
        cap = s.layer(top, "sphere", contrast=1.6, sep="outer", sep_idx=0)
        cap.ellipse(cx, cy, 3.2, 2.7, fat=0.05)
        ys, xs = cap.mask.nonzero()
        for (x, y) in zip(xs, ys):
            r = math.hypot((x + 0.5 - cx) / 3.2, (y + 0.5 - cy) / 2.7)
            if r > 0.62:
                ang = math.degrees(math.atan2(y + 0.5 - cy, x + 0.5 - cx))
                cap.nudge([(x, y)], -1 if int((ang + 360) // 40) % 2 else 1)
    return s.render()


