def gear_mask(cx, cy, r_out=3.6, r_in=2.4, hole=1.1, teeth=8, phase=0.0, w=16, h=16):
    """Boolean mask of a little cog: ring + square-ish teeth + hub hole."""
    import math
    import numpy as np
    m = np.zeros((h, w), bool)
    for y in range(h):
        for x in range(w):
            dx, dy = x + 0.5 - cx, y + 0.5 - cy
            r = math.hypot(dx, dy)
            a = (math.degrees(math.atan2(dy, dx)) - phase) % (360.0 / teeth)
            tooth = a < (360.0 / teeth) * 0.5
            if hole < r <= r_in + 0.35 or (r_in < r <= r_out + 0.2 and tooth):
                m[y, x] = True
    return m


def _log(s, x0, y0, length, bark=BARK, end=END):
    """A log lying left-right, 4 px tall, end grain (3 x 4 ellipse) on its right end."""
    b = s.layer(bark, "cyl", axis=0, contrast=2.0, sep="outer", sep_idx=0)
    b.rect(x0, y0, x0 + length - 1, y0 + 3)
    b.px((x0, y0), (x0, y0 + 3), add=False)
    e = s.layer(end, "flat", base=2, lit=3, dark=1, sep="outer")
    ex = x0 + length - 1
    e.px((ex, y0), (ex + 1, y0), (ex - 1, y0 + 1), (ex, y0 + 1), (ex + 1, y0 + 1), (ex + 2, y0 + 1),
         (ex - 1, y0 + 2), (ex, y0 + 2), (ex + 1, y0 + 2), (ex + 2, y0 + 2), (ex, y0 + 3), (ex + 1, y0 + 3))
    e.set([(ex, y0 + 1), (ex + 1, y0 + 2)], 1)   # ring
    e.set([(ex + 1, y0 + 1)], 0)                   # pith
    return s


