def rubber():
    rb = Ramp(C.RUBBER)
    s = L.Sprite()
    tyre = s.layer(rb, "inflate", contrast=2.4, bevel=2, bias=0.5)
    tyre.ellipse(8.0, 8.5, 6.0, 5.0, fat=0.05)
    tyre.ellipse(8.0, 8.5, 2.6, 2.0, add=False)
    # tread blocks: lighter nubs along the top/left of the tread
    for (x, y) in ((4, 4), (7, 3), (10, 3), (12, 5), (3, 7), (2, 9)):
        if tyre.mask[y, x]:
            tyre.nudge([(x, y)], 1)
